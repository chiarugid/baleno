// Traduzioni dell'interfaccia (italiano / inglese).
// Ogni chiave nasce come coppia [italiano, inglese]: non può esistere in una sola lingua.
// I segnaposto {nome} vengono sostituiti da t(chiave, { nome: valore }).
// I termini tecnici (header, broadcast, wildcard, refresher, payload type, prefix…)
// restano in inglese in entrambe le lingue.

export const LANGS = ['it', 'en'];
export const DEFAULT_LANG = 'it';
const LOCALES = { it: 'it-IT', en: 'en-GB' };

const IT = {};
const EN = {};
export const MESSAGES = { it: IT, en: EN };

function add(prefix, entries) {
  for (const [key, pair] of Object.entries(entries)) {
    const [it, en] = pair;
    IT[prefix + key] = it;
    EN[prefix + key] = en;
  }
}

let current = DEFAULT_LANG;
const listeners = new Set();

export function getLang() {
  return current;
}

export function locale() {
  return LOCALES[current];
}

export function isLang(value) {
  return LANGS.includes(value);
}

// Lingua iniziale: parametro nell'URL > preferenza salvata > italiano.
export function resolveLang(urlLang, storedLang) {
  if (isLang(urlLang)) return urlLang;
  if (isLang(storedLang)) return storedLang;
  return DEFAULT_LANG;
}

export function setLang(lang) {
  if (!isLang(lang) || lang === current) return;
  current = lang;
  for (const fn of listeners) fn(lang);
}

export function onLangChange(fn) {
  listeners.add(fn);
  return () => listeners.delete(fn);
}

export function t(key, vars) {
  const text = MESSAGES[current][key] ?? IT[key];
  if (text == null) return key;
  if (!vars) return text;
  return text.replace(/\{(\w+)\}/g, (m, name) => (name in vars ? String(vars[name]) : m));
}

// Singolare/plurale: usa chiave.one se n = 1, altrimenti chiave.other.
export function tn(key, n, vars = {}) {
  return t(`${key}.${Number(n) === 1 ? 'one' : 'other'}`, { n, ...vars });
}

// Testo di una chiave in tutte le lingue (per la ricerca strumenti).
export function tAll(key) {
  return LANGS.map((lang) => MESSAGES[lang][key] ?? '').join(' ');
}

